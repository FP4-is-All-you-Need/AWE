import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync('../data/modular/powers.json','utf8'));
const set=data.sets.find(s=>s.magnitude_bits===53&&s.verification.moduli[0]===107);
const six=data.solutions.find(s=>s.modulus===343&&s.products.length===6&&s.weights.B.join(',')==='1,7,49');
const five=data.solutions.find(s=>s.modulus===343&&s.products.length===5&&s.weights.A.join(',')==='1,14,98');
const hole=data.solutions.find(s=>s.modulus===343&&s.measurement.holes.B.length>0);
for(const lang of ['en','ja'])test(`saved prime powers, folded planes and hole candidates ${lang}`,async({page})=>{
 test.setTimeout(120000);
 await page.goto(`/?lang=${lang}&b=53&K=8192`);
 await page.locator('[data-section="modset-catalog"] > summary').click();
 await page.locator('[name="modset_id"]').selectOption(set.id);
 await expect(page.locator('.paper-lane [data-tile-id]')).toHaveCount(16);
 await expect(page.locator('.paper-lane')).toContainText(lang==='en'?'Build only':'build だけ');
 await page.locator(`.paper-lane [data-tile-id="${six.id}"]`).click();
 const detail=page.locator('.paper-lane .construction-detail');
 await expect(detail.locator('[data-expansion]')).toHaveAttribute('data-expansion',six.id);
 const cells=detail.locator('[data-expansion-cell^="0:"]');await expect(cells).toHaveCount(9);
 expect(await cells.evaluateAll(es=>es.filter(e=>Number(e.getAttribute('data-cell-coefficient'))!==0).length)).toBe(6);
 await detail.locator('[data-section^="flow."] > summary').click();
 await expect(detail.locator('[data-plane-flow="A"] [data-flow-plane]')).toHaveCount(3);
 await page.locator('.paper-lane').screenshot({path:`../build/screens/powers-343-six-${lang}.png`});
 await page.locator('[name="swap_toggle"]').click();
 const candidate=page.locator(`[data-candidate="${five.id}"]`);await expect(candidate).toBeVisible();
 await candidate.locator('[name="replacement_id"]').click();
 await expect(detail.locator('[data-expansion]')).toHaveAttribute('data-expansion',five.id);
 await expect(detail.locator('[data-plane-moduli]')).toContainText('49,343,7,49');
 await detail.locator('[data-section^="flow."] > summary').click();
 await expect(detail.locator('[data-plane-flow="A"] [data-flow-plane]')).toHaveCount(4);
 await page.locator('[name="swap_close"]').click();
 await page.locator('.paper-lane').screenshot({path:`../build/screens/powers-343-five-${lang}.png`});
 await page.reload();await expect(page.locator('.paper-lane [data-expansion]')).toHaveAttribute('data-expansion',five.id);
 await page.locator('[name="swap_toggle"]').click();
 await page.locator(`[data-candidate="${hole.id}"] [name="replacement_id"]`).click();
 await expect(page.locator('.paper-lane .construction-detail')).toContainText('5.248');
 await expect(page.locator('.paper-lane [data-compact-grid]')).toHaveCount(8);
 await expect(page.locator('.paper-lane [data-correction-source-cost]')).toContainText('1.499');
 await page.locator('[name="swap_close"]').click();
 await page.locator('.paper-lane').screenshot({path:`../build/screens/powers-343-holes-${lang}.png`});
});
test('78-bit saved sets expose prime powers as swap candidates without inventing a set',async({page})=>{
 await page.goto('/?lang=en&b=78&K=8192&swap=1&same_modulus=0&prime=7');
 await expect(page.locator(`[data-candidate="${five.id}"]`)).toBeVisible();
 await page.locator('.swap-panel').screenshot({path:'../build/screens/powers-78-candidates.png'});
 await expect(page.locator(`[data-candidate="${five.id}"] [name="replacement_id"]`)).toBeDisabled();
 await page.locator('[name="swap_close"]').click();
 await page.locator('.paper-lane [data-tile-modulus="161"]').click();
 await page.locator('[name="swap_toggle"]').click();
 await expect(page.locator(`[data-candidate="${five.id}"] [name="replacement_id"]`)).toBeEnabled();
 await page.locator(`[data-candidate="${five.id}"] [name="replacement_id"]`).click();
 await expect(page.locator('.paper-lane [data-expansion]')).toHaveAttribute('data-expansion',five.id);
 await page.reload();await expect(page.locator('.paper-lane [data-expansion]')).toHaveAttribute('data-expansion',five.id);
});

test('fourth powers keep ten triangular products and measured plane values',async({page})=>{
 const selected=data.sets.find(s=>s.magnitude_bits===53&&s.solution_ids.length===15);
 const fourth=data.solutions.find(s=>s.modulus===625);
 await page.goto('/?b=53&modset_id='+selected.id);
 await page.locator(`.paper-lane [data-tile-id="${fourth.id}"]`).click();
 const detail=page.locator('.paper-lane .construction-detail');
 await expect(detail.locator('[data-compact-expansion]')).toBeVisible();
 await detail.locator('[name="expansion_layout"]').selectOption('products');
 const cells=detail.locator('[data-expansion-cell^="0:"]');await expect(cells).toHaveCount(16);
 expect(await cells.evaluateAll(es=>es.filter(e=>Number(e.getAttribute('data-cell-coefficient'))!==0).length)).toBe(10);
 await detail.locator('[name="plane_values"]').check();
 await expect(detail.locator('.selected-values [data-plane-band="A.0"] [data-used="true"]')).toHaveCount(fourth.measurement.plane_values.A[0].length);
 await page.locator('.paper-lane').screenshot({path:'../build/screens/powers-625-fourth.png'});
});
