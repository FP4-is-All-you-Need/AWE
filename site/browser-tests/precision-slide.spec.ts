import {test,expect} from '@playwright/test';

test('slide 5 bit cells sit below precision, keep fixed order on selection, and keep source fills and white boundaries',async({page})=>{
 await page.goto('/?lang=ja');
 const band=page.locator('[data-section=precision-bands]'),rows=band.locator('[data-format]');
 await expect(band).toHaveAttribute('open','');
 expect(await band.evaluate(e=>e.previousElementSibling?.querySelector('select[name=precision]')!==null)).toBe(true);
 await expect(rows.first()).toHaveAttribute('data-format','fp64');
 const cells=rows.first().locator('[data-bit]');await expect(cells).toHaveCount(64);
 const geometry=await band.locator('[data-bit] rect').evaluateAll(nodes=>nodes.map(n=>({w:n.getAttribute('width'),fill:n.getAttribute('fill'),stroke:n.getAttribute('stroke')})));
 expect(new Set(geometry.map(c=>c.w)).size).toBe(1);
 expect(Number(geometry[0].w)).toBeLessThan(36);
 expect(new Set(geometry.map(c=>c.fill))).toEqual(new Set(['#EEEEEE','#CDEFFC','#FFE2BD']));
 expect(geometry.every(c=>c.stroke==='#FFFFFF')).toBe(true);
 await expect(rows.first().locator('[data-bit=S]')).toContainText('S');
 await expect(rows.first().locator('[data-field-label=E] .katex')).toHaveCount(1);
 await expect(rows.first().locator('[data-field-label=M] .katex')).toHaveCount(1);
 await expect(band.locator('[data-precision-legend="1"]')).toContainText('指数');
 await page.locator('select[name=precision]').selectOption('fp8');
 await expect(rows.first()).toHaveAttribute('data-format','fp64');
 await expect(band.locator('[data-format=fp8] [data-bit]')).toHaveCount(8);
 await expect(band.locator('[data-format=fp8] [data-b-marker]')).toHaveAttribute('data-used-stored','3');
 await page.locator('select[name=precision]').selectOption('fp64');await page.locator('input[name=b]').fill('47');
 await expect(rows.first()).toHaveAttribute('data-format','fp64');
 await expect(rows.first().locator('[data-b-marker]')).toHaveAttribute('data-b','47');
 await expect(rows.first().locator('[data-b-marker]')).toHaveAttribute('data-used-stored','46');
 await page.reload();await expect(rows.first()).toHaveAttribute('data-format','fp64');
 await rows.filter({has:page.locator('[data-bit=E10]')}).click();
 await expect(page.locator('select[name=precision]')).toHaveValue('fp64');
 await expect(rows.first()).toHaveAttribute('data-format','fp64');
 await page.screenshot({path:'build/screens/precision-slide5-fp64.png'});
 await page.locator('select[name=precision]').selectOption('fp4');
 await expect(rows.first()).toHaveAttribute('data-format','fp64');
 await expect(band.locator('[data-format=fp4] [data-bit=M0]')).toContainText('M');
 await page.locator('input[name=b]').focus();await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:'build/screens/precision-slide5-fp4.png'});
 await page.locator('select[name=lang]').selectOption('en');
 await expect(band.locator('[data-precision-legend="1"]')).toContainText('Exponent');
 await page.setViewportSize({width:390,height:844});
 expect(await band.locator('.precision-figure').evaluate(e=>e.scrollWidth>e.clientWidth)).toBe(false);
 expect(await band.locator('[data-field-label] .svg-math').evaluateAll(nodes=>nodes.every(n=>parseFloat(getComputedStyle(n).fontSize)>=14))).toBe(true);
 await page.screenshot({path:'build/screens/precision-slide5-narrow.png'});
 await expect(page.locator('.katex-error')).toHaveCount(0);
});
