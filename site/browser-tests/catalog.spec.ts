test('board round trip verifies inside worker and rejects a damaged construction',async({page})=>{
 await page.goto('/');await expect(page.locator('#catalog .product')).toHaveCount(6);
 await page.getByRole('button',{name:'選択中の解を S に',exact:true}).click();
 await expect(page.locator('.tier').first().locator('div button')).toHaveCount(1);
 const saved=await page.evaluate(()=>localStorage.getItem('awe-board-v1'));
 expect(saved).toBeTruthy();
 await page.reload();await expect(page.getByRole('status')).toContainText('1 件をブラウザで厳密検証');
 await expect(page.locator('.tier').first().locator('div button')).toHaveCount(1);
 await page.getByLabel('JSON を読み込む',{exact:true}).setInputFiles({name:'board.json',mimeType:'application/json',buffer:Buffer.from(saved!)});
 await expect(page.getByRole('status')).toContainText('1 件をブラウザで厳密検証');
 const bad=JSON.parse(saved!);bad.solutions[0].products[0].numerator++;
 await page.getByLabel('JSON を読み込む',{exact:true}).setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(bad))});
 await expect(page.getByRole('status')).toContainText('読み込みを拒否しました: identity_failed');
 await expect(page.getByRole('complementary',{name:'未検証の読み込み'})).toContainText('identity_failed');
 await expect(page.locator('.tier').first().locator('div button')).toHaveCount(1);
});
