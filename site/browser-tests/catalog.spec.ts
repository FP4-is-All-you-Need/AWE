test('a locally verified construction survives reload without catalog lookup',async({page})=>{
 await page.goto('/');await expect(page.locator('#catalog .product')).toHaveCount(6);
 await page.getByRole('button',{name:'選択中の解を S に',exact:true}).click();
 const raw=await page.evaluate(()=>JSON.parse(localStorage.getItem('awe-board-v1')!).solutions[0]);
 const previous=raw.id;raw.domain={A:[-3,3],B:[-3,3]};
 await page.getByLabel('JSON を読み込む',{exact:true}).setInputFiles({name:'local.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(raw))});
 await expect(page.getByRole('status')).toContainText('1 件をブラウザで厳密検証');
 await expect(page.locator('#catalog .detail')).toContainText('A [-3, 3]');
 expect(new URL(page.url()).searchParams.get('id')).not.toBe(previous);
 await page.reload();await expect(page.getByRole('status')).toContainText('1 件をブラウザで厳密検証');
 await expect(page.locator('#catalog .detail')).toContainText('A [-3, 3]');
 await expect(page.locator('.error')).toHaveCount(0);
});

